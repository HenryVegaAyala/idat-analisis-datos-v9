# ciclos con python

# ciclo for -> Recorre cada elemento de una lista

frutas = ["fresa", "limón", "piña", "mango", "sandia"]

# for -> indica que vamos a repetir algo
# variable fruta -> es una variable temporal que irá tomando cada elemento
# in -> significa "dentro de"
# frutas -> es nuestra lista
# : -> indica que empieza el bloque de instrucciones
# print -> es una función que imprime en pantalla

for fruta in frutas:
    print(f"Nombre de la fruta: {fruta}")